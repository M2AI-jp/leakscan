/** JPドメインは登録資格で組織の種別が決まっている。名前で判定できなかったときの
 *  手がかりとして使う（推測ではなく、登録規則上そうである）。 */
const BY_DOMAIN = [
  [/\.(ac|ed)\.jp$/, '教育'],
  [/\.(lg|go)\.jp$/, '公共'],
  [/^(pref|city|town|village|metro|ward)\./, '公共'],
  [/\.(or|gr)\.jp$/, '団体']
];

/**
 * 業種を推定する。
 * @param {string[]} texts 組織名・サービス名など
 * @returns {string} 業種。判定できなければ '未分類'
 */
export function guessSector(...texts) {
  const s = texts.filter(Boolean).join(' ').normalize('NFKC');
  for (const [sector, re] of RULES) if (re.test(s)) return sector;
  return '未分類';
}

/**
 * 名前で判定できなかったとき、照合ドメインの属性から業種を補う。
 * @param {string[]} domains 照合ドメイン
 * @returns {string} 業種。判定できなければ '未分類'
 */
export function sectorFromDomain(domains) {
  for (const d of domains || []) {
    for (const [re, sector] of BY_DOMAIN) if (re.test(String(d).toLowerCase())) return sector;
  }
  return '未分類';
}
